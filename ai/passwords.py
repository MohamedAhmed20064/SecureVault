"""AI feature 3: password strength classifier (Random Forest on hand-made features, trained on generated passwords)."""
import math, random, re, string
from collections import Counter
from sklearn.ensemble import RandomForestClassifier

COMMON = ["password", "qwerty", "iloveyou", "admin", "welcome", "football", "ahmed", "mohamed", "mohammed", "egypt", "cairo", "master", "dragon", "monkey",
          "letmein", "login", "summer", "winter", "princess", "superman", "love", "hello", "freedom", "batman", "shadow", "sunshine", "computer", "student", "12345", "123456"]
SEQ = ["123", "234", "345", "456", "567", "678", "789", "abc", "bcd", "cde", "qwe", "wer", "asd", "sdf", "zxc"]
_WORDS = COMMON + ["orange", "guitar", "planet", "coffee", "rocket", "castle", "pencil", "garden", "silver", "window", "tiger", "violin", "mountain", "giraffe", "elephant", "bridge"]
FEATURE_NAMES = ["length", "lower", "upper", "digits", "symbols", "unique_ratio", "entropy_bits", "has_common_word", "has_sequence", "max_repeat_ratio", "ends_with_year", "digits_only"]

def features(pw):
    n = len(pw) or 1; low = pw.lower(); cnt = Counter(pw)
    entropy = -sum(v / n * math.log2(v / n) for v in cnt.values()) * n
    return [len(pw), sum(c.islower() for c in pw), sum(c.isupper() for c in pw), sum(c.isdigit() for c in pw), sum(not c.isalnum() for c in pw),
            len(cnt) / n, entropy, int(any(w in low for w in COMMON)), int(any(s in low for s in SEQ)), max(cnt.values()) / n,
            int(bool(re.search(r"(19|20)\d\d$", pw))), int(pw.isdigit())]

def _gen(rng, label):
    A = string.ascii_letters + string.digits + "!@#$%^&*-_"; k = rng.random()
    if label == "weak":
        if k < .35: return rng.choice(COMMON[:24]) + rng.choice(["", "1", "12", "123", "2005", "2020", "007"])
        if k < .6: return "".join(rng.choice(string.digits) for _ in range(rng.randint(4, 9)))
        if k < .8: return "".join(rng.choice(string.ascii_lowercase) for _ in range(rng.randint(3, 7)))
        return rng.choice("abcdefghij") * rng.randint(4, 10)
    if label == "medium":
        if k < .6: return rng.choice(_WORDS).capitalize() + rng.choice("@#_!-") + str(rng.randint(10, 9999))
        return "".join(rng.choice(string.ascii_lowercase + string.digits) for _ in range(rng.randint(8, 11)))
    if k < .6: return "".join(rng.choice(A) for _ in range(rng.randint(12, 20)))
    ws = [rng.choice(_WORDS) for _ in range(rng.randint(3, 4))]; ws = [w.capitalize() if rng.random() < .5 else w for w in ws]
    return rng.choice("-._#").join(ws) + rng.choice("-.") + str(rng.randint(10, 99999))

def make_dataset(seed, per_class):
    rng = random.Random(seed); X, y = [], []
    for label in ("weak", "medium", "strong"):
        for _ in range(per_class): X.append(features(_gen(rng, label))); y.append(label)
    return X, y

# hand-written test passwords (never generated by the training code)
HAND_TEST = [("123456", "weak"), ("password", "weak"), ("qwerty123", "weak"), ("ahmed2005", "weak"), ("iloveyou", "weak"), ("11111111", "weak"),
             ("Ahmed@2024", "medium"), ("Summer#2023", "medium"), ("Cairo_1999", "medium"), ("zebra4455xt", "medium"), ("pencil9x8k2m", "medium"), ("Guitar!4821", "medium"),
             ("k7#Qz!p9Lm2$vR8x", "strong"), ("correct-horse-battery-staple-91", "strong"), ("Xv9$mT2@qLp7!nWz", "strong"),
             ("purple.Giraffe.Window.58.Tent", "strong"), ("8fJ!2kQz#Lp0aVw9", "strong"), ("blue-Elephant-Drum-Sky-4721", "strong")]

def build_model():
    return RandomForestClassifier(n_estimators=120, random_state=0)

_X, _y = make_dataset(42, 600)
_MODEL = build_model().fit(_X, _y)

def _tips(pw):
    f = dict(zip(FEATURE_NAMES, features(pw))); t = []
    if f["length"] < 12: t.append("Use at least 12 characters")
    if f["upper"] == 0: t.append("Add an uppercase letter")
    if f["digits"] == 0: t.append("Add a digit")
    if f["symbols"] == 0: t.append("Add a symbol like ! or #")
    if f["has_common_word"]: t.append("Avoid common words and names")
    if f["has_sequence"]: t.append("Avoid sequences like 123 or abc")
    if f["max_repeat_ratio"] > .4 and f["length"] > 3: t.append("Avoid repeating the same character")
    return t[:3]

def password_strength(pw):
    if not pw: return {"label": None, "score": 0, "tips": []}
    p = dict(zip(_MODEL.classes_, _MODEL.predict_proba([features(pw)])[0]))
    label, score = max(p, key=p.get), round(100 * (p.get("medium", 0) * .5 + p.get("strong", 0)))
    if pw.lower() in COMMON or (pw.isdigit() and len(pw) < 10): label, score = "weak", min(score, 20)   # hard safety rule
    return {"label": label, "score": score, "tips": _tips(pw)}
